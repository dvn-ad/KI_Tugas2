RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36]

def xtime(a: int) -> int:
    return ((a << 1) ^ 0x1B) & 0xFF if (a & 0x80) else (a << 1) & 0xFF

def gmul(a: int, b: int) -> int:
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi_bit = a & 0x80
        a = (a << 1) & 0xFF
        if hi_bit:
            a ^= 0x1B
        b >>= 1
    return p

def sub_bytes(state):
    for r in range(4):
        for c in range(4):
            state[r][c] = S_BOX[state[r][c]]

def inv_sub_bytes(state):
    for r in range(4):
        for c in range(4):
            state[r][c] = INV_S_BOX[state[r][c]]

def shift_rows(state):
    state[1] = state[1][1:] + state[1][:1]
    state[2] = state[2][2:] + state[2][:2]
    state[3] = state[3][3:] + state[3][:3]

def inv_shift_rows(state):
    state[1] = state[1][-1:] + state[1][:-1]
    state[2] = state[2][-2:] + state[2][:-2]
    state[3] = state[3][-3:] + state[3][:-3]

def mix_columns(state):
    for c in range(4):
        s0, s1, s2, s3 = state[0][c], state[1][c], state[2][c], state[3][c]
        t = s0 ^ s1 ^ s2 ^ s3
        state[0][c] ^= t ^ xtime(s0 ^ s1)
        state[1][c] ^= t ^ xtime(s1 ^ s2)
        state[2][c] ^= t ^ xtime(s2 ^ s3)
        state[3][c] ^= t ^ xtime(s3 ^ s0)

def inv_mix_columns(state):
    for c in range(4):
        s0, s1, s2, s3 = state[0][c], state[1][c], state[2][c], state[3][c]
        state[0][c] = gmul(s0, 0x0E) ^ gmul(s1, 0x0B) ^ gmul(s2, 0x0D) ^ gmul(s3, 0x09)
        state[1][c] = gmul(s0, 0x09) ^ gmul(s1, 0x0E) ^ gmul(s2, 0x0B) ^ gmul(s3, 0x0D)
        state[2][c] = gmul(s0, 0x0D) ^ gmul(s1, 0x09) ^ gmul(s2, 0x0E) ^ gmul(s3, 0x0B)
        state[3][c] = gmul(s0, 0x0B) ^ gmul(s1, 0x0D) ^ gmul(s2, 0x09) ^ gmul(s3, 0x0E)

def add_round_key(state, rkey):
    for r in range(4):
        for c in range(4):
            state[r][c] ^= rkey[r][c]

def key_expansion(key_bytes):
    w = [list(key_bytes[i:i+4]) for i in range(0, 16, 4)]
    for i in range(4, 44):
        temp = w[i-1][:]
        if i % 4 == 0:
            temp = temp[1:] + temp[:1]
            temp = [S_BOX[b] for b in temp]
            temp[0] ^= RCON[i // 4]
        w.append([w[i-4][b] ^ temp[b] for b in range(4)])
    
    round_keys = []
    for r in range(0, 44, 4):
        matrix = [[w[r+c][row] for c in range(4)] for row in range(4)]
        round_keys.append(matrix)
    return round_keys

def aes_encrypt_block(plaintext_16bytes, round_keys):
    state = [[plaintext_16bytes[r + 4*c] for c in range(4)] for r in range(4)]
    
    add_round_key(state, round_keys[0])
    for round_idx in range(1, 10):
        sub_bytes(state)
        shift_rows(state)
        mix_columns(state)
        add_round_key(state, round_keys[round_idx])
        
    sub_bytes(state)
    shift_rows(state)
    add_round_key(state, round_keys[10])
    
    output = bytearray(16)
    for r in range(4):
        for c in range(4):
            output[r + 4*c] = state[r][c]
    return bytes(output)

def aes_decrypt_block(ciphertext_16bytes, round_keys):
    state = [[ciphertext_16bytes[r + 4*c] for c in range(4)] for r in range(4)]
    
    add_round_key(state, round_keys[10])
    for round_idx in range(9, 0, -1):
        inv_shift_rows(state)
        inv_sub_bytes(state)
        add_round_key(state, round_keys[round_idx])
        inv_mix_columns(state)
        
    inv_shift_rows(state)
    inv_sub_bytes(state)
    add_round_key(state, round_keys[0])
    
    output = bytearray(16)
    for r in range(4):
        for c in range(4):
            output[r + 4*c] = state[r][c]
    return bytes(output)

def pad_pkcs7(data: bytes, block_size: int = 16) -> bytes:
    pad_len = block_size - (len(data) % block_size)
    return data + bytes([pad_len] * pad_len)

def unpad_pkcs7(data: bytes, block_size: int = 16) -> bytes:
    if not data or len(data) % block_size != 0:
        raise ValueError("Invalid padded block length")
    pad_len = data[-1]
    if pad_len < 1 or pad_len > block_size:
        raise ValueError("Invalid PKCS#7 padding byte value")
    if data[-pad_len:] != bytes([pad_len] * pad_len):
        raise ValueError("Corrupted PKCS#7 padding")
    return data[:-pad_len]

def normalize_key(key_str: str) -> bytes:
    key_bytes = key_str.encode('ascii', errors='ignore')
    if len(key_bytes) < 16:
        key_bytes = key_bytes.ljust(16, b' ')
    else:
        key_bytes = key_bytes[:16]
    return key_bytes

def aes_encrypt(plaintext_str: str, key_str: str) -> str:
    key = normalize_key(key_str)
    round_keys = key_expansion(key)
    raw_data = plaintext_str.encode('ascii')
    padded = pad_pkcs7(raw_data, 16)
    
    ciphertext = bytearray()
    for i in range(0, len(padded), 16):
        ciphertext.extend(aes_encrypt_block(padded[i:i+16], round_keys))
    return ciphertext.hex().upper()

def aes_decrypt(ciphertext_hex: str, key_str: str) -> str:
    key = normalize_key(key_str)
    round_keys = key_expansion(key)
    cipher_bytes = bytes.fromhex(ciphertext_hex.strip())
    
    if len(cipher_bytes) % 16 != 0:
        raise ValueError("Ciphertext length must be a multiple of 16 bytes")
        
    decrypted = bytearray()
    for i in range(0, len(cipher_bytes), 16):
        decrypted.extend(aes_decrypt_block(cipher_bytes[i:i+16], round_keys))
        
    unpadded = unpad_pkcs7(bytes(decrypted), 16)
    return unpadded.decode('ascii')


